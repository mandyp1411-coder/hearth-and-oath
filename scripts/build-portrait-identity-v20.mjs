import {readFile,writeFile,readdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {PORTRAIT_CATALOG,AGE_SUPPLEMENT_CATALOG} from '../dist/js/portrait-catalog.js';
const root=new URL('../',import.meta.url),read=async path=>JSON.parse(await readFile(new URL(path,root),'utf8'));
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
const native={};
const supplements=[];
for(const file of (await readdir(new URL('reference-art/preset-v20/supplements/',root))).filter(f=>f.endsWith('.json')).sort()){
  const s=await read('reference-art/preset-v20/supplements/'+file),r=await read('reference-art/preset-v20/registration/'+s.id+'.json');
  if(s.entries.length!==64||r.cells.length!==64)throw Error('Incomplete supplement '+s.id);
  const meta=await read('reference-art/preset-v20/identity/'+s.id+'.json');
  supplements.push({...s,src:`./art/presets/${s.id}.avif`,width:r.width,height:r.height,cells:r.cells.map(c=>c.source)});
  for(const e of s.entries)if(e.cell<0||e.cell>63||!['infant','child','adolescent','adult','elder'].includes(e.stage))throw Error('Invalid supplement entry '+s.id);
}
for(const atlas of [...Object.entries(PORTRAIT_CATALOG).map(([id,a])=>({id,...a})),...AGE_SUPPLEMENT_CATALOG,...supplements]){
  const m=await read('reference-art/preset-v20/identity/'+atlas.id+'.json'),bytes=await readFile(new URL('dist/'+atlas.src.replace('./',''),root));
  if(m.sourceSha256!==sha(bytes)||m.cells.length!==64||m.cells.some((c,i)=>c.cell!==i||!['dark','light','grey','covered','bald','uncertain'].includes(c.hairTone)))throw Error('Invalid observed identity metadata '+atlas.id);
  native[atlas.id]=m.cells.map(({cell,...c})=>c);
}
await writeFile(new URL('dist/js/portrait-identity-v20.js',root),`// Observed native pixels. Generated by scripts/build-portrait-identity-v20.mjs.\nexport const PORTRAIT_IDENTITY_V20 = Object.freeze(${JSON.stringify(native)});\nexport const LIFECYCLE_SUPPLEMENTS_V20 = Object.freeze(${JSON.stringify(supplements)});\n`);
console.log(`Validated ${Object.keys(native).length} atlases and ${supplements.length*64} new complete portraits.`);
