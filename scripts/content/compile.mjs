// Compile validated content into ES modules the engine can import, one per
// kind: dist/js/content/<kind>.js. Each module has a named export of frozen
// data (`SCENES`, `THREADS`, …) and a `<KIND>_BY_ID` index. Named exports,
// not `export default`: scripts/build-offline.mjs inlines every module by
// stripping `export ` and destructuring `import { … } from './x.js'`, and a
// default export would not survive that. The modules import nothing, so the
// import graph stays acyclic. Design assets are not compiled: the engine does
// not read them.
//
//   node scripts/content/compile.mjs [--content content] [--out dist/js/content]
//
// Refuses to write when the tree has errors. Not run against dist/ in v0.70:
// no engine content exists yet; the test compiles fixtures into a temp folder.
import { mkdirSync, writeFileSync, rmSync, existsSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { validateTree, walk, project } from './validate.mjs';
import { KINDS } from './schema.mjs';

export const EXPORT_NAMES = Object.freeze({ scene: 'SCENES', thread: 'THREADS', foe: 'FOES', place: 'PLACES', landmark: 'LANDMARKS', ambition: 'AMBITIONS', play: 'PLAYS', dialogue: 'DIALOGUES' });

/** Gather the items of every compiled kind from a validated tree. */
export function gather(contentDir, root = project) {
  const byKind = {};
  for (const abs of walk(contentDir)) {
    const doc = JSON.parse(readFileSync(abs, 'utf8'));
    if (!doc || Array.isArray(doc) || !KINDS.includes(doc.kind) || doc.kind === 'design-asset') continue;
    (byKind[doc.kind] ||= []).push(...doc.items.map(it => ({ ...it, source: path.relative(root, abs).split(path.sep).join('/') })));
  }
  for (const list of Object.values(byKind)) list.sort((a, b) => a.id < b.id ? -1 : a.id > b.id ? 1 : 0);
  return byKind;
}

const FREEZE = `const freeze = v => { if (v && typeof v === 'object') { for (const k of Object.keys(v)) freeze(v[k]); Object.freeze(v); } return v; };`;
export function moduleSource(kind, items) {
  const name = EXPORT_NAMES[kind];
  return [
    `// Generated by scripts/content/compile.mjs from the content tree (${items.length} ${kind}${items.length === 1 ? '' : 's'}). Do not edit; edit the JSON and compile.`,
    FREEZE,
    `export const ${name} = freeze(${JSON.stringify(items, null, 2)});`,
    `export const ${name}_BY_ID = freeze(Object.fromEntries(${name}.map(x => [x.id, x])));`,
    '',
  ].join('\n');
}

/** Validate, then write one module per kind into `outDir`. Returns { report, written } or throws on errors. */
export function compile(contentDir, outDir, root = project) {
  const report = validateTree(contentDir, root);
  if (report.errors) { const e = new Error(`The content tree has ${report.errors} error${report.errors === 1 ? '' : 's'}; nothing compiled.`); e.report = report; throw e; }
  const byKind = gather(contentDir, root), written = [];
  mkdirSync(outDir, { recursive: true });
  for (const kind of Object.keys(EXPORT_NAMES)) {
    const file = path.join(outDir, `${kind}.js`), items = byKind[kind];
    if (!items?.length) { if (existsSync(file)) rmSync(file); continue; } // a kind that left the tree leaves dist
    writeFileSync(file, moduleSource(kind, items));
    written.push({ kind, file, items: items.length });
  }
  return { report, written };
}

function args(argv) {
  const o = { content: 'content', out: 'dist/js/content' };
  for (let i = 0; i < argv.length; i++) { const a = argv[i]; if (['--content', '--out'].includes(a)) o[a.slice(2)] = argv[++i]; else throw new Error(`Unknown argument ${a}`); }
  return o;
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const o = args(process.argv.slice(2));
  try {
    const { written } = compile(path.resolve(project, o.content), path.resolve(project, o.out));
    for (const w of written) console.log(`${w.kind}: ${w.items} → ${path.relative(project, w.file)}`);
    if (!written.length) console.log('Nothing to compile: the tree holds no engine content.');
  } catch (e) {
    console.error(e.message);
    for (const row of e.report?.errorRows || []) console.error(`  ${row.file} ${row.path}: ${row.message}`);
    process.exit(1);
  }
}
