#!/usr/bin/env python3
"""Materialize retained, source-checksummed saves for the optional Node profile.

No game state, money, HP, age, calendar, people or history is invented or edited.
The only new states in the Node harness are generated by the public birth API.
"""
import argparse
import gzip
import hashlib
import json
from pathlib import Path
import tarfile

parser = argparse.ArgumentParser()
parser.add_argument('--out', type=Path)
args = parser.parse_args()
repo = Path(__file__).resolve().parent.parent
out = (args.out or repo / 'artifacts/performance/fixtures').resolve()
out.mkdir(parents=True, exist_ok=True)
manifest = json.loads((repo / 'docs/playtest/action-records-manifest.json').read_text())
archive = repo / 'docs/playtest/api-action-records.tar.gz'
assert hashlib.sha256(archive.read_bytes()).hexdigest() == manifest['sha256'], 'Historical archive checksum mismatch'
records = {item['path']: item for item in manifest['records']}
provenance = []

def save(ident, state, source):
    file = ident + '.json'
    (out / file).write_text(json.dumps(state, separators=(',', ':'), ensure_ascii=False))
    provenance.append(dict(id=ident, file=file, age=state['age'], generation=state['dynasty']['generation'], journalEntries=len(state['journal']), historical=True, **source))

with tarfile.open(archive, 'r:gz') as tar:
    for ident, member, field in [
        ('elder103', 'after/childhood/childhood-06-elder-scholar.json', 'state'),
        ('successor2', 'story/story-01-renew-replay.json', 'finalState'),
    ]:
        raw = tar.extractfile(member).read()
        assert hashlib.sha256(raw).hexdigest() == records[member]['sha256'], member + ' checksum mismatch'
        save(ident, json.loads(raw)[field], dict(source=str(archive.relative_to(repo)), member=member, field=field, sourceSha256=records[member]['sha256']))
for index in range(3):
    source = repo / f'tests/fixtures/earned-balance/root-{index}.json.gz'
    record = json.loads(gzip.decompress(source.read_bytes()))
    save(f'adult{index}', record['state'], dict(source=str(source.relative_to(repo)), sourceSha256=hashlib.sha256(source.read_bytes()).hexdigest(), sourceStateHash=record.get('stateHash'), evidenceClass=record.get('evidenceClass')))
source = repo / 'docs/playtest/roadmap-v27/connected-journey-final-save.json.gz'
save('journey957', json.loads(gzip.decompress(source.read_bytes())), dict(source=str(source.relative_to(repo)), sourceSha256=hashlib.sha256(source.read_bytes()).hexdigest()))
(out / 'provenance.json').write_text(json.dumps(provenance, indent=2) + '\n')
print('Prepared six retained fixture copies and provenance; no engine imported or simulation run.')
