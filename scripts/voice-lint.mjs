// The voice lint reads every string the player might see and reports the ones
// in the ledger's voice rather than the game's. v0.70 reports only; the rules
// are in scripts/lib/voice-rules.mjs so later releases can fail the build on
// them and the content validator can share them.
//
//   node scripts/voice-lint.mjs [--snapshot docs/measures/voice-lint-v070.md] [--strict] [--quiet]
//
// Writes artifacts/voice-lint/voice-lint.json and voice-lint.md (gitignored).
// --snapshot also writes the Markdown to the given path, the committed
// baseline. Exit code is 0 unless --strict, which exits 1 on any hit.
//
// What is scanned: dist/js/**/*.js, except dist/offline/ and the generated art
// catalogues (a module is a catalogue when its name says portrait, -art-,
// catalog or atlas and it is over 128 KB, or one of its first three lines is a
// comment saying "Generated from", "Generated by" or "Generated only"). The
// skipped files are listed in the report.
//
// How strings are found: a small tokenizer walks each module and skips //
// and /* */ comments and regex literals, keeping '…', "…" and `…` literals.
// A template literal becomes one string with PLACEHOLDER ({…}) where each
// ${…} expression was, and the strings inside those expressions are found
// too. A slash starts a regex when the previous significant token is a
// punctuator that cannot end an operand, a keyword like return or typeof, or
// the start of the file; it is division after an identifier, a number, a
// closing bracket or a string. Known limits: a regex right after `)` (as in
// `if (x) /re/.test(y)`) is read as division, which may swallow the rest of
// the line, and a `}` closing an object literal before a division is read as
// a statement end; neither occurs in this codebase's style. Nothing is
// evaluated, so text built by concatenation or lookup is seen in its parts.
//
// What counts as player-facing: the string with its HTML tags removed (the
// values of aria-label, title, placeholder and alt attributes kept, since a
// reader hears them) has at least three words and a space, and reads as
// prose: a capital letter, sentence punctuation or an ordinary function word
// ("the", "your", "and"…). That rejects identifiers, kebab-case and
// snake_case tokens, class lists ("secondary small"), selectors beginning
// with . # or [, URLs and file paths, data keys and tags without text. It
// still admits some labels for HTML attributes and some developer-only
// strings (console messages, error reasons); those are listed as hits when
// they say a forbidden phrase, and the Markdown report names the patterns
// seen so far.
import { readdirSync, readFileSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';
import { VOICE_RULES, PLACEHOLDER, lintText } from './lib/voice-rules.mjs';

export const PROJECT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

// ---------------------------------------------------------------- tokenizer

const REGEX_KEYWORDS = new Set(['return', 'typeof', 'instanceof', 'in', 'of', 'new', 'delete', 'void', 'throw', 'case', 'do', 'else', 'yield', 'await']);
// Punctuators after which a slash starts a regex. `}` is read as a statement
// end (an object literal divided by something does not happen here).
const REGEX_AFTER = new Set(['(', ',', '=', ':', '[', '!', '&', '|', '?', '{', '}', ';', '+', '-', '*', '%', '<', '>', '~', '^']);
const ESCAPES = { n: '\n', t: '\t', r: '\r', b: '\b', f: '\f', v: '\v', 0: '\0' };

function unescape(body) {
  return body.replace(/\\(u\{([0-9a-fA-F]+)\}|u([0-9a-fA-F]{4})|x([0-9a-fA-F]{2})|\r?\n|.)/gs, (all, esc, brace, u4, x2) => {
    if (brace) return String.fromCodePoint(parseInt(brace, 16));
    if (u4) return String.fromCharCode(parseInt(u4, 16));
    if (x2) return String.fromCharCode(parseInt(x2, 16));
    if (esc === '\n' || esc === '\r\n') return '';
    return ESCAPES[esc] ?? esc;
  });
}

/** Every string literal in `source`: { text, line, kind: 'string' | 'template', placeholders }. */
export function extractStrings(source) {
  const out = [];
  let i = 0, line = 1;
  const n = source.length;

  function scanCode(stopAtBrace) {
    let depth = 0, prev = '', word = '';
    while (i < n) {
      const c = source[i];
      if (c === '\n') { line++; i++; continue; }
      if (c === '/' && source[i + 1] === '/') { while (i < n && source[i] !== '\n') i++; continue; }
      if (c === '/' && source[i + 1] === '*') {
        i += 2;
        while (i < n && !(source[i] === '*' && source[i + 1] === '/')) { if (source[i] === '\n') line++; i++; }
        i += 2; continue;
      }
      if (c === "'" || c === '"') { readString(c); prev = 'v'; word = ''; continue; }
      if (c === '`') { readTemplate(); prev = 'v'; word = ''; continue; }
      if (c === '/') {
        const regex = prev === '' || REGEX_AFTER.has(prev) || (prev === 'a' && REGEX_KEYWORDS.has(word));
        if (regex) { readRegex(); prev = 'v'; word = ''; continue; }
        i++; prev = '/'; word = ''; continue;
      }
      if (stopAtBrace) {
        if (c === '{') depth++;
        else if (c === '}') { if (depth === 0) return; depth--; }
      }
      if (/[A-Za-z_$]/.test(c)) {
        let j = i; while (j < n && /[\w$]/.test(source[j])) j++;
        word = source.slice(i, j); i = j; prev = 'a'; continue;
      }
      if (/[0-9]/.test(c)) { while (i < n && /[\w.]/.test(source[i])) i++; prev = 'v'; word = ''; continue; }
      if (!/\s/.test(c)) { prev = c; word = ''; }
      i++;
    }
  }

  function readString(quote) {
    const start = line; let j = i + 1;
    while (j < n && source[j] !== quote) {
      if (source[j] === '\\') { if (source[j + 1] === '\n') line++; j += 2; continue; }
      if (source[j] === '\n') break; // an unterminated string: stop at the line end
      j++;
    }
    out.push({ text: unescape(source.slice(i + 1, j)), line: start, kind: 'string', placeholders: 0 });
    i = j + 1;
  }

  function readTemplate() {
    const start = line; let text = '', placeholders = 0;
    i++;
    while (i < n) {
      const c = source[i];
      if (c === '\\') { text += unescape(source.slice(i, i + 2)); if (source[i + 1] === '\n') line++; i += 2; continue; }
      if (c === '`') { i++; break; }
      if (c === '$' && source[i + 1] === '{') { i += 2; scanCode(true); i++; text += PLACEHOLDER; placeholders++; continue; }
      if (c === '\n') line++;
      text += c; i++;
    }
    out.push({ text, line: start, kind: 'template', placeholders });
  }

  function readRegex() {
    let j = i + 1, inClass = false;
    while (j < n && source[j] !== '\n') {
      const c = source[j];
      if (c === '\\') { j += 2; continue; }
      if (inClass) { if (c === ']') inClass = false; }
      else if (c === '[') inClass = true;
      else if (c === '/') { j++; break; }
      j++;
    }
    while (j < n && /[a-z]/.test(source[j])) j++;
    i = j;
  }

  scanCode(false);
  return out;
}

// ------------------------------------------------------------ player-facing

const FUNCTION_WORDS = new Set(['a', 'an', 'the', 'of', 'to', 'in', 'and', 'or', 'but', 'your', 'you', 'is', 'are', 'was', 'were', 'be', 'with', 'for', 'at', 'on', 'no', 'not', 'this', 'that', 'it', 'its', 'as', 'by', 'from', 'has', 'have', 'had', 'will', 'who', 'what', 'when', 'where', 'they', 'them', 'their', 'he', 'she', 'his', 'her', 'we', 'our', 'if', 'then', 'than', 'there', 'here', 'one', 'all', 'some', 'any', 'more', 'most', 'into', 'over', 'under', 'before', 'after', 'while', 'until', 'again', 'still', 'yet', 'so', 'too', 'very', 'can', 'cannot', 'could', 'would', 'should', 'may', 'might', 'must', 'do', 'does', 'did', 'done']);
const KEPT_ATTRIBUTES = /\b(?:aria-label|aria-description|title|placeholder|alt)\s*=\s*(?:"([^"]*)"|'([^']*)')/g;

/** The words a reader meets: tags removed, a few spoken attributes kept, entities and space tidied. */
export function readableText(raw) {
  const spoken = [];
  for (const m of raw.matchAll(KEPT_ATTRIBUTES)) spoken.push(m[1] ?? m[2] ?? '');
  const stripped = raw.replace(/<[^<>]*>/g, ' ');
  return [stripped, ...spoken].join(' ')
    .replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;|&apos;/g, '’')
    .replace(/\s+/g, ' ').trim();
}

const WORD = /[\p{L}\p{N}][\p{L}\p{N}’'-]*/gu;

/** True when a string reads as prose a player might see; see the header. */
export function isPlayerFacing(raw) {
  if (typeof raw !== 'string') return false;
  const trimmed = raw.trim();
  if (trimmed.length < 7) return false;
  if (/^[.#[]/.test(trimmed) && !/^\.\.\.|^\.\s|^\[object/.test(trimmed)) return false; // selectors
  if (/^(?:[a-z][a-z0-9+.-]*:\/\/|\.{0,2}\/|data:|mailto:)/i.test(trimmed)) return false; // URLs and paths
  if (/^[\w.$-]+(?:\.[a-z0-9]+)$/i.test(trimmed)) return false; // file names
  const text = readableText(trimmed);
  if (!text.includes(' ')) return false;
  const words = text.match(WORD) || [];
  const placeholders = text.split(PLACEHOLDER).length - 1;
  if (!words.length || words.length + placeholders < 3) return false; // a filled-in slot is a word; a string of only slots is not
  const tokens = text.split(' ');
  if (tokens.every(t => /^[a-z0-9]+(?:[-_][a-z0-9]+)+$/.test(t))) return false; // kebab/snake lists
  const prose = /[A-Z\p{Lu}]/u.test(text) || /[.,;:!?…’'"“”]/.test(text) || words.some(w => FUNCTION_WORDS.has(w.toLowerCase()));
  if (!prose) return false; // an all-lowercase token list: class names, ids, keys
  if (/^[a-z]+(?:[A-Z][a-z]*)+\b/.test(text) && words.length < 5) return false; // camelCase keys with a word or two
  return true;
}

// --------------------------------------------------------------------- scan

const CATALOGUE_NAME = /portrait|-art-|catalog|atlas/i;
const CATALOGUE_BYTES = 128 * 1024;

function* walk(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(full);
    else if (entry.isFile() && entry.name.endsWith('.js')) yield full;
  }
}

/** Why a module is left out, or null to scan it. */
export function skipReason(file, size, head) {
  const rel = path.relative(PROJECT, file).split(path.sep).join('/');
  if (rel.startsWith('dist/offline/')) return 'the offline bundle is built from the modules already scanned';
  if (CATALOGUE_NAME.test(path.basename(file)) && size > CATALOGUE_BYTES) return `art catalogue, ${(size / 1024).toFixed(0)} KB`;
  if (/^\/\/.*\bGenerated (?:from|by|only)\b/m.test(head.split('\n').slice(0, 3).join('\n'))) return 'generated module; no authored text';
  return null;
}

/** Lint one module's source: the player-facing strings and their hits. */
export function lintSource(source, file = '<source>') {
  const strings = extractStrings(source).filter(s => isPlayerFacing(s.text));
  const hits = [];
  for (const s of strings) for (const h of lintText(readableText(s.text))) hits.push({ file, line: s.line, rule: h.id, severity: h.severity, match: h.match, text: trimForReport(readableText(s.text)) });
  return { strings: strings.length, hits };
}

function trimForReport(text, max = 220) {
  return text.length <= max ? text : text.slice(0, max - 1) + '…';
}

/** Scan dist/js under `project` and build the report object. */
export function scanRepo(project = PROJECT) {
  const root = path.join(project, 'dist', 'js');
  const modules = [], skipped = [], hits = [];
  let strings = 0;
  for (const file of [...walk(root)].sort()) {
    const rel = path.relative(project, file).split(path.sep).join('/');
    const size = statSync(file).size;
    const source = readFileSync(file, 'utf8');
    const why = skipReason(file, size, source.slice(0, 600));
    if (why) { skipped.push({ file: rel, bytes: size, reason: why }); continue; }
    const result = lintSource(source, rel);
    strings += result.strings;
    hits.push(...result.hits);
    modules.push({ file: rel, strings: result.strings, hits: result.hits.length });
  }
  const byRule = {};
  for (const r of VOICE_RULES) byRule[r.id] = 0;
  for (const h of hits) byRule[h.rule]++;
  const bySeverity = { audit: 0, placeholder: 0 };
  for (const h of hits) bySeverity[h.severity]++;
  const worst = modules.filter(m => m.hits).sort((a, b) => b.hits - a.hits || a.file.localeCompare(b.file)).slice(0, 20);
  return {
    version: readVersion(project), generatedAt: new Date().toISOString(),
    scanned: modules.length, skipped, strings, hits: hits.length, bySeverity, byRule,
    rules: VOICE_RULES.map(r => ({ id: r.id, severity: r.severity, pattern: r.pattern.source, reason: r.reason })),
    worst, modules, findings: hits,
  };
}

function readVersion(project) {
  try { return JSON.parse(readFileSync(path.join(project, 'package.json'), 'utf8')).version; } catch { return null; }
}

// ------------------------------------------------------------------ reports

const md = s => String(s).replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');

/** The Markdown report: what was read, what was found, where. */
export function renderMarkdown(report) {
  const lines = [];
  lines.push('# Voice lint', '');
  lines.push(`Source version ${report.version ?? '?'}, run ${report.generatedAt.slice(0, 10)}. The lint (\`scripts/voice-lint.mjs\`) reads every string literal in \`dist/js\` that reads as prose and reports the phrases in \`scripts/lib/voice-rules.mjs\`: the ledger's words where the chronicle should speak, and text that was never finished. In v0.70 it reports only; \`--strict\` is how a later release turns the failures on.`, '');
  lines.push('## The count', '');
  lines.push(`- Modules scanned: ${report.scanned} (${report.skipped.length} skipped, listed below)`);
  lines.push(`- Player-facing strings: ${report.strings}`);
  lines.push(`- Hits: ${report.hits} (${report.bySeverity.audit} audit, ${report.bySeverity.placeholder} placeholder)`);
  lines.push(`- Modules with a hit: ${report.modules.filter(m => m.hits).length}`, '');
  lines.push('## Hits by rule', '', '| Rule | Severity | Hits | Why it is a hit |', '|---|---|---:|---|');
  for (const r of report.rules.slice().sort((a, b) => report.byRule[b.id] - report.byRule[a.id] || a.id.localeCompare(b.id))) lines.push(`| \`${r.id}\` | ${r.severity} | ${report.byRule[r.id]} | ${md(r.reason)} |`);
  lines.push('', '## The worst twenty modules', '', '| Module | Strings | Hits |', '|---|---:|---:|');
  for (const m of report.worst) lines.push(`| \`${m.file}\` | ${m.strings} | ${m.hits} |`);
  lines.push('', '## Hits by module', '');
  const grouped = new Map();
  for (const h of report.findings) { if (!grouped.has(h.file)) grouped.set(h.file, []); grouped.get(h.file).push(h); }
  for (const [file, rows] of [...grouped.entries()].sort((a, b) => b[1].length - a[1].length || a[0].localeCompare(b[0]))) {
    lines.push(`### \`${file}\` — ${rows.length}`, '');
    for (const h of rows) lines.push(`- line ${h.line} · \`${h.rule}\` (“${md(h.match)}”): ${md(h.text)}`);
    lines.push('');
  }
  lines.push('## Skipped', '');
  for (const s of report.skipped) lines.push(`- \`${s.file}\` — ${s.reason}`);
  lines.push('', '## Known false positives', '');
  lines.push('The lint reads source, not the screen. Hits that are not the ledger speaking, seen in this release:', '');
  lines.push('- A person doing the recording, in the ordinary sense: “The jailer recorded your request for a moon chamber.” (`recorded`).');
  lines.push('- `compatible` in plain English: “Choose up to three compatible traits.”, “keep healing work compatible with time for family”.');
  lines.push('- `prediction` inside an authored story: the astrologer’s predictions in `personal-stories-v27.js`, the oracle in the encounter designs.');
  lines.push('- Design notes shipped inside a content module (`encounter-design-v27.js`’s notes: “requiredTags is proposed suitability metadata…”). The player never sees them, but they travel with the game.');
  lines.push('- Strings the UI never shows but that read as prose: validation errors, console messages, blocked-action reasons. They are counted among the player-facing strings and are hits only when they say a forbidden phrase.', '');
  lines.push('Two limits of reading source. Text built from parts is seen in its parts: the pager’s “Offers: 1–4 of 4 saved” is `\'Offers\'`, `{…}–{…} of {…}` and `\' saved\'` in `journal-pagination.js`, so `offers-count` and `saved-trailer` see none of it and `range-of-total` sees the middle; a check that feeds the rendered screen to `lintText` would see it whole. And a string of three words or more is taken as prose, so a two-word label (“Recipe category”) is not read at all.', '');
  lines.push('The rules stay precise rather than broad. A hit that is in the game’s voice is a reason to narrow the rule, not to rewrite the line.', '');
  return lines.join('\n');
}

// --------------------------------------------------------------------- main

export function main(argv = process.argv.slice(2)) {
  let snapshot = null, strict = false, quiet = false;
  for (let at = 0; at < argv.length; at++) {
    if (argv[at] === '--snapshot') snapshot = argv[++at];
    else if (argv[at] === '--strict') strict = true;
    else if (argv[at] === '--quiet') quiet = true;
    else throw new Error('Usage: node scripts/voice-lint.mjs [--snapshot path.md] [--strict] [--quiet]');
  }
  const report = scanRepo(PROJECT);
  const outDir = path.join(PROJECT, 'artifacts', 'voice-lint');
  mkdirSync(outDir, { recursive: true });
  const markdown = renderMarkdown(report);
  writeFileSync(path.join(outDir, 'voice-lint.json'), JSON.stringify(report, null, 2) + '\n');
  writeFileSync(path.join(outDir, 'voice-lint.md'), markdown);
  if (snapshot) { const target = path.resolve(PROJECT, snapshot); mkdirSync(path.dirname(target), { recursive: true }); writeFileSync(target, markdown); }
  if (!quiet) {
    console.log(`Voice lint: ${report.strings} player-facing strings in ${report.scanned} modules (${report.skipped.length} skipped); ${report.hits} hits (${report.bySeverity.audit} audit, ${report.bySeverity.placeholder} placeholder).`);
    for (const m of report.worst.slice(0, 10)) console.log(`  ${String(m.hits).padStart(4)}  ${m.file}`);
    console.log(`Report: artifacts/voice-lint/voice-lint.md${snapshot ? ` and ${snapshot}` : ''}`);
  }
  return strict && report.hits > 0 ? 1 : 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) process.exit(main());
